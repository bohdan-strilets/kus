import { z } from 'zod'

import {
	MAX_EXERCISES_PER_WORKOUT,
	MAX_SET_REPS,
	MAX_SET_WEIGHT_KG,
	MAX_SETS_PER_EXERCISE,
	MAX_WORKOUT_MINUTES,
} from '../ai/workout-tools.js'
import { exerciseKindSchema, muscleGroupSchema } from './enums.js'
import { PROGRAM_NAME_MAX_LENGTH, PROGRAM_DISTANCE_M_MAX } from './programs.js'
import { programLastSetSchema } from './programs-api.js'
import { workoutResponseSchema } from './workouts.js'

/** How many days back a workout can be logged by the form (today included as day 0). */
export const FORM_MAX_DAYS_BACK = 3

const MAX_SET_DURATION_SEC = MAX_WORKOUT_MINUTES * 60

const exerciseInputShape = {
	exerciseId: z.uuid().nullable().default(null),
	/** A template exercise of the session's template; checked by the backend. */
	templateExerciseId: z.uuid().nullable().default(null),
	name: z.string().trim().min(1).max(PROGRAM_NAME_MAX_LENGTH),
	kind: exerciseKindSchema,
	muscleGroup: muscleGroupSchema.nullable().default(null),
	/** null = unknown; true means no weight on any set. */
	isBodyweight: z.boolean().nullable().default(null),
	durationMin: z.number().int().min(1).max(MAX_WORKOUT_MINUTES).nullable().default(null),
	distanceM: z.number().int().min(1).max(PROGRAM_DISTANCE_M_MAX).nullable().default(null),
}

const setInputShape = {
	reps: z.number().int().min(1).max(MAX_SET_REPS).nullable().default(null),
	weightKg: z.number().min(0).max(MAX_SET_WEIGHT_KG).nullable().default(null),
	durationSec: z.number().int().min(1).max(MAX_SET_DURATION_SEC).nullable().default(null),
	distanceM: z.number().int().min(1).max(PROGRAM_DISTANCE_M_MAX).nullable().default(null),
	isWarmup: z.boolean().default(false),
}

const hasNoWeightedSet = (input: {
	isBodyweight: boolean | null
	sets: readonly { weightKg: number | null }[]
}): boolean => input.isBodyweight !== true || input.sets.every((set) => set.weightKg === null)

const BODYWEIGHT_WEIGHT_ISSUE = {
	path: ['sets'],
	message: 'BODYWEIGHT_HAS_WEIGHT',
}

export const liveSetInputSchema = z.object({
	...setInputShape,
	/** ISO: when the set was marked done. */
	doneAt: z.iso.datetime().nullable().default(null),
})
export type LiveSetInput = z.infer<typeof liveSetInputSchema>

export const liveExerciseInputSchema = z
	.object({
		/** Generated by the client once per exercise of the session; the key of the upsert. */
		clientKey: z.uuid(),
		...exerciseInputShape,
		sets: z.array(liveSetInputSchema).max(MAX_SETS_PER_EXERCISE),
	})
	.refine(hasNoWeightedSet, BODYWEIGHT_WEIGHT_ISSUE)
export type LiveExerciseInput = z.infer<typeof liveExerciseInputSchema>

/** PUT /live-workouts/:id: the whole part of the session the live mode leads. */
export const liveWorkoutUpdateSchema = z.object({
	/** `editedAt` the client last saw; another value means the chat replaced the session meanwhile. */
	knownEditedAt: z.iso.datetime().nullable(),
	exercises: z.array(liveExerciseInputSchema).max(MAX_EXERCISES_PER_WORKOUT),
})
export type LiveWorkoutUpdate = z.infer<typeof liveWorkoutUpdateSchema>

/**
 * POST /live-workouts/:id/finish: the body is optional. An offline phone sends its snapshot with
 * the time of the tap, so the finish is one atomic call.
 */
export const liveWorkoutFinishSchema = z.preprocess(
	// no body at all (an old client) reads as an empty one
	(body) => body ?? {},
	z
		.object({
			/** ISO: when «Завершити» was tapped; clamped to [start or last done set, now] by the server. */
			finishedAt: z.iso.datetime().optional(),
			/** As in the PUT (null allowed); required with `exercises`, else the stamp is not checked. */
			knownEditedAt: z.iso.datetime().nullable().optional(),
			exercises: liveWorkoutUpdateSchema.shape.exercises.optional(),
		})
		.refine(
			({ exercises, knownEditedAt }) => exercises === undefined || knownEditedAt !== undefined,
			{
				path: ['knownEditedAt'],
				message: 'Required',
			},
		),
)
export type LiveWorkoutFinish = z.infer<typeof liveWorkoutFinishSchema>

/** POST /live-workouts: a session by a template, or an empty one. */
export const liveWorkoutStartSchema = z.object({ templateId: z.uuid().nullable() })
export type LiveWorkoutStart = z.infer<typeof liveWorkoutStartSchema>

/** Path of the /live-workouts/:id routes. */
export const liveWorkoutParamsSchema = z.object({ id: z.uuid() })

export const liveConflictReasonSchema = z.enum(['EDITED', 'FINISHED'])
export type LiveConflictReason = z.infer<typeof liveConflictReasonSchema>

export const formSetInputSchema = z.object(setInputShape)
export type FormSetInput = z.infer<typeof formSetInputSchema>

export const formExerciseInputSchema = z
	.object({
		...exerciseInputShape,
		sets: z.array(formSetInputSchema).max(MAX_SETS_PER_EXERCISE),
	})
	.refine(hasNoWeightedSet, BODYWEIGHT_WEIGHT_ISSUE)
export type FormExerciseInput = z.infer<typeof formExerciseInputSchema>

/** POST /workout-forms: a finished session at once; the days and the future are checked by the backend. */
export const workoutFormSchema = z.object({
	/** Makes a repeated request return the first answer. */
	clientRequestId: z.uuid(),
	templateId: z.uuid().nullable(),
	localDate: z.iso.date(),
	/** `HH:mm` in the user's time zone. */
	startTime: z.string().regex(/^([01]\d|2[0-3]):[0-5]\d$/),
	durationMin: z.number().int().min(1).max(MAX_WORKOUT_MINUTES),
	exercises: z.array(formExerciseInputSchema).max(MAX_EXERCISES_PER_WORKOUT),
})
export type WorkoutForm = z.infer<typeof workoutFormSchema>

/** One exercise of the template the live session follows, with the last time and the hint. */
export const livePlanExerciseSchema = z.object({
	templateExerciseId: z.uuid(),
	exerciseId: z.uuid().nullable(),
	name: z.string(),
	kind: exerciseKindSchema,
	muscleGroup: muscleGroupSchema.nullable(),
	isBodyweight: z.boolean().nullable().default(null),
	sets: z.number().int().nullable(),
	repsMin: z.number().int().nullable(),
	repsMax: z.number().int().nullable(),
	weightKg: z.number().nullable(),
	progressStepKg: z.number().nullable(),
	restSec: z.number().int().nullable(),
	durationMin: z.number().int().nullable(),
	distanceM: z.number().int().nullable(),
	lastSets: z.array(programLastSetSchema).nullable(),
	progressHintKg: z.number().nullable().default(null),
})
export type LivePlanExercise = z.infer<typeof livePlanExerciseSchema>

export const liveWorkoutResponseSchema = z.object({
	workout: workoutResponseSchema,
	/** To send back as `knownEditedAt`. */
	editedAt: z.iso.datetime().nullable(),
	templateName: z.string().nullable(),
	/** Empty for a session without a template. */
	plan: z.array(livePlanExerciseSchema),
})
export type LiveWorkoutResponse = z.infer<typeof liveWorkoutResponseSchema>

/** A finished session: the answer of the form and of a live finish with work in it. */
export const workoutFinishedSchema = z.object({
	workout: workoutResponseSchema,
	/** The Kusik message that carries the summary card. */
	messageId: z.uuid(),
	hasNewRecord: z.boolean(),
	discarded: z.literal(false).optional(),
})
export type WorkoutFinished = z.infer<typeof workoutFinishedSchema>

/** «Завершити» with no set marked done: the session is removed, no summary, nothing to show. */
export const workoutDiscardedSchema = z.object({ discarded: z.literal(true) })
export type WorkoutDiscarded = z.infer<typeof workoutDiscardedSchema>

/**
 * Answer of finishing a live session (and of the form, always the finished shape). The finished
 * shape stays as it was; `discarded: true` is the other one.
 */
export const workoutFinishResponseSchema = z.union([workoutFinishedSchema, workoutDiscardedSchema])
export type WorkoutFinishResponse = z.infer<typeof workoutFinishResponseSchema>
